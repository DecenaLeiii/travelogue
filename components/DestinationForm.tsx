import { useState, FormEvent } from 'react';
import { useTranslation } from '../lib/i18n';
import AdminImageField from './AdminImageField';

export type DestinationFormData = {
  name: string;
  slug: string;
  region: string;
  location: string;
  short_description: string;
  content: string;
  best_time_to_visit: string;
  highlights: string;
  travel_tips: string;
  cover_image: string;
  gallery_images: string[];
  categories: { title: string; items: { name: string; description: string; image: string }[] }[];
  related_slugs: string;
  featured: boolean;
  published: boolean;
};

const empty: DestinationFormData = {
  name: '',
  slug: '',
  region: '',
  location: '',
  short_description: '',
  content: '',
  best_time_to_visit: '',
  highlights: '',
  travel_tips: '',
  cover_image: '',
  gallery_images: [],
  categories: [],
  related_slugs: '',
  featured: false,
  published: true,
};

type Props = {
  initial?: DestinationFormData;
  onSubmit: (data: DestinationFormData) => void;
  saving?: boolean;
};

export default function DestinationForm({ initial, onSubmit, saving }: Props) {
  const { t } = useTranslation();
  const [form, setForm] = useState<DestinationFormData>(initial || empty);

  const set = (key: keyof DestinationFormData, value: string | boolean) => {
    setForm((f) => ({ ...f, [key]: value }));
  };

  const handleSubmit = (e: FormEvent) => {
    e.preventDefault();
    onSubmit({
      ...form,
      highlights: form.highlights,
      travel_tips: form.travel_tips,
      cover_image: form.cover_image,
      gallery_images: form.gallery_images,
      categories: form.categories,
      related_slugs: form.related_slugs,
    });
  };

  return (
    <form className="admin-form" onSubmit={handleSubmit}>
      <div className="admin-form-actions">
        <button type="submit" disabled={saving}>{saving ? t('saving') : t('saveDestination')}</button>
      </div>

      <label>
        {t('nameLabel')} *
        <input required value={form.name} onChange={(e) => set('name', e.target.value)} />
      </label>
      <label>
        {t('slugLabel')}
        <input value={form.slug} onChange={(e) => set('slug', e.target.value)} placeholder={t('autoGeneratedIfEmpty')} />
      </label>
      <div className="admin-form-row">
        <label>
          {t('regionLabel')}
          <input value={form.region} onChange={(e) => set('region', e.target.value)} />
        </label>
        <label>
          {t('locationLabel')}
          <input value={form.location} onChange={(e) => set('location', e.target.value)} />
        </label>
      </div>
      <label>
        {t('shortOverview')}
        <textarea rows={2} value={form.short_description} onChange={(e) => set('short_description', e.target.value)} />
      </label>
      <label>
        {t('fullContent')}
        <textarea rows={6} value={form.content} onChange={(e) => set('content', e.target.value)} />
      </label>
      <label>
        {t('bestTimeToVisit')}
        <input value={form.best_time_to_visit} onChange={(e) => set('best_time_to_visit', e.target.value)} />
      </label>
      <label>
        {t('highlightsOnePerLine')}
        <textarea rows={4} value={form.highlights} onChange={(e) => set('highlights', e.target.value)} />
      </label>
      <label>
        {t('travelTipsOnePerLine')}
        <textarea rows={4} value={form.travel_tips} onChange={(e) => set('travel_tips', e.target.value)} />
      </label>
      <section className="destination-images-editor">
        <div>
          <h2>Destination photos</h2>
          <p>The cover appears on the homepage preview and as the destination page hero. Gallery photos appear inside the destination page.</p>
        </div>
        <div className="destination-cover-editor">
          <h3>Homepage preview and page cover</h3>
          <AdminImageField label="Cover image" value={form.cover_image} onChange={(value) => set('cover_image', value)} />
        </div>
        <div className="destination-gallery-editor">
          <div className="destination-gallery-heading">
            <div>
              <h3>Destination page gallery</h3>
              <p>Add as many gallery photos as you need.</p>
            </div>
            <button type="button" className="details-btn" onClick={() => setForm((current) => ({ ...current, gallery_images: [...current.gallery_images, ''] }))}>Add gallery photo</button>
          </div>
          {form.gallery_images.map((image, index) => (
            <div className="destination-gallery-row" key={`gallery-${index}`}>
              <AdminImageField label={`Gallery photo ${index + 1}`} value={image} onChange={(value) => setForm((current) => ({ ...current, gallery_images: current.gallery_images.map((photo, photoIndex) => photoIndex === index ? value : photo) }))} />
              <button type="button" className="details-btn danger-button" onClick={() => setForm((current) => ({ ...current, gallery_images: current.gallery_images.filter((_, photoIndex) => photoIndex !== index) }))}>Remove</button>
            </div>
          ))}
        </div>
      </section>
      <section className="destination-images-editor local-food-editor">
        <div className="destination-gallery-heading">
          <div>
            <h2>Destination categories</h2>
            <p>Create sections such as local food, activities, or best things to do. They appear below the photo gallery.</p>
          </div>
          <button type="button" className="details-btn" onClick={() => setForm((current) => ({ ...current, categories: [...current.categories, { title: '', items: [] }] }))}>Add category</button>
        </div>
        {form.categories.map((category, categoryIndex) => (
          <article className="destination-category-editor" key={`category-${categoryIndex}`}>
            <div className="destination-gallery-heading">
              <label className="destination-category-title">
                Category title
                <input value={category.title} placeholder="e.g. Local food to try" onChange={(event) => setForm((current) => ({ ...current, categories: current.categories.map((item, itemIndex) => itemIndex === categoryIndex ? { ...item, title: event.target.value } : item) }))} />
              </label>
              <button type="button" className="details-btn danger-button" onClick={() => setForm((current) => ({ ...current, categories: current.categories.filter((_, itemIndex) => itemIndex !== categoryIndex) }))}>Remove category</button>
            </div>
            {category.items.map((entry, itemIndex) => (
              <div className="local-food-editor-row" key={`category-${categoryIndex}-item-${itemIndex}`}>
                <div className="local-food-fields">
                  <label>
                    Name
                    <input value={entry.name} onChange={(event) => setForm((current) => ({ ...current, categories: current.categories.map((item, index) => index === categoryIndex ? { ...item, items: item.items.map((child, childIndex) => childIndex === itemIndex ? { ...child, name: event.target.value } : child) } : item) }))} />
                  </label>
                  <label>
                    Description
                    <textarea rows={2} value={entry.description} onChange={(event) => setForm((current) => ({ ...current, categories: current.categories.map((item, index) => index === categoryIndex ? { ...item, items: item.items.map((child, childIndex) => childIndex === itemIndex ? { ...child, description: event.target.value } : child) } : item) }))} />
                  </label>
                  <AdminImageField label={`Photo ${itemIndex + 1}`} value={entry.image} onChange={(value) => setForm((current) => ({ ...current, categories: current.categories.map((item, index) => index === categoryIndex ? { ...item, items: item.items.map((child, childIndex) => childIndex === itemIndex ? { ...child, image: value } : child) } : item) }))} />
                </div>
                <button type="button" className="details-btn danger-button" onClick={() => setForm((current) => ({ ...current, categories: current.categories.map((item, index) => index === categoryIndex ? { ...item, items: item.items.filter((_, childIndex) => childIndex !== itemIndex) } : item) }))}>Remove item</button>
              </div>
            ))}
            <button type="button" className="details-btn" onClick={() => setForm((current) => ({ ...current, categories: current.categories.map((item, index) => index === categoryIndex ? { ...item, items: [...item.items, { name: '', description: '', image: '' }] } : item) }))}>Add item</button>
          </article>
        ))}
      </section>
      <label>
        {t('relatedSlugsCommaSeparated')}
        <input value={form.related_slugs} onChange={(e) => set('related_slugs', e.target.value)} />
      </label>
      <div className="admin-form-row">
        <label className="checkbox-label">
          <input type="checkbox" checked={form.featured} onChange={(e) => set('featured', e.target.checked)} />
          {t('featured')}
        </label>
        <label className="checkbox-label">
          <input type="checkbox" checked={form.published} onChange={(e) => set('published', e.target.checked)} />
          {t('publishedLabel')}
        </label>
      </div>
    </form>
  );
}
