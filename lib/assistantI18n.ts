const DICTS: Record<Lang, AssistantDict> = { en, tl, es, zh, hi, ar, ceb, ilo, hil, war, pam, bik, pag }
const LOCAL_FALLBACK = new Set<Lang>(['ilo', 'hil', 'war', 'pam', 'bik', 'pag'])

export function normalizeLang(value: unknown): Lang {
  return typeof value === 'string' && value in DICTS ? (value as Lang) : 'en'
}

export function atext(lang: Lang, key: string, vars: Record<string, string> = {}) {
  const raw = DICTS[lang]?.[key] ?? (LOCAL_FALLBACK.has(lang) ? tl[key] : undefined) ?? en[key] ?? key
  return raw.replace(/\{(\w+)\}/g, (_, name) => vars[name] ?? '')
}

const LOCALES: Record<Lang, string> = { en: 'en', tl: 'fil', es: 'es', zh: 'zh', hi: 'hi', ar: 'ar', ceb: 'ceb', ilo: 'ilo', hil: 'hil', war: 'war', pam: 'pam', bik: 'bik', pag: 'pag' }
const MONTH_KEYS = ['january', 'february', 'march', 'april', 'may', 'june', 'july', 'august', 'september', 'october', 'november', 'december']

export function monthLabel(lang: Lang, month: string) {
  const index = MONTH_KEYS.indexOf(month.toLowerCase())
  if (index < 0) return month
  try {
    const name = new Intl.DateTimeFormat(LOCALES[lang], { month: 'long' }).format(new Date(2024, index, 15))
    return name || month
  } catch {
    return month.charAt(0).toUpperCase() + month.slice(1)
  }
}
