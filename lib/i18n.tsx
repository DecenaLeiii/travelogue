const I18nContext = createContext({
  lang: 'en' as Lang,
  setLang: (l: Lang) => {},
  t: (k: string) => k,
});

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('en');

  useEffect(() => {
    const saved = typeof window !== 'undefined' ? localStorage.getItem('travelogue_lang') : null;
    if (saved && ['en','zh','hi','es','ar','tl','ceb','ilo','hil','war','pam','bik','pag'].includes(saved)) setLangState(saved as Lang);
  }, []);

  const setLang = (l: Lang) => {
    setLangState(l);
    if (typeof window !== 'undefined') localStorage.setItem('travelogue_lang', l);
  };

  const t = (k: string) => {
    const current = translations[lang] ?? translations.en ?? {};
    return current[k] || translations.en?.[k] || k;
  };

  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export function useTranslation() {
  return useContext(I18nContext);
}

